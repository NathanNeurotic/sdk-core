#!/usr/bin/env python3
"""Writes src/inflate_data.h: a raw deflate stream of 64 KiB of generated text and tables, for the inflate kernel."""

import os
import random
import zlib

SIZE = 65536

words = ("player enemy level score texture vertex sound music frame buffer sprite camera light shadow model "
         "packet render update input pad memory card save load stage world boss item weapon health magic").split()

rng = random.Random(12345)
out = bytearray()
while len(out) < SIZE:
    if rng.random() < 0.8:
        line = " ".join(rng.choice(words) for _ in range(rng.randint(3, 12)))
        out += (line.capitalize() + ".\n").encode()
    else:
        out += bytes(rng.randrange(256) for _ in range(rng.randint(8, 64)))
data = bytes(out[:SIZE])

comp = zlib.compressobj(9, zlib.DEFLATED, -15)
stream = comp.compress(data) + comp.flush()

h = 2166136261
for b in data:
    h = ((h ^ b) * 16777619) & 0xffffffff

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "inflate_data.h")
with open(path, "w", newline="\n") as f:
    f.write("/* Generated by gen_inflate_data.py: raw deflate (zlib level 9) of %d bytes, FNV-1a %08x. */\n"
            % (SIZE, h))
    f.write("#define INFLATE_OUT_BYTES %d\n" % SIZE)
    f.write("static const unsigned char inflate_in[%d] __attribute__((aligned(64))) = {\n" % len(stream))
    for i in range(0, len(stream), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in stream[i:i + 16]) + ",\n")
    f.write("};\n")
print("%d -> %d bytes, FNV-1a %08x" % (SIZE, len(stream), h))
