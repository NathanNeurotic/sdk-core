#!/usr/bin/env python3
"""Writes src/iop/image.c: a 64 KiB FAT12 volume holding HELLO.TXT, stored as its non-zero sectors."""

import os
import struct

SECTOR = 512
TOTAL = 128
HELLO = b"hello from the ramdisk\n"


def boot_sector():
    bs = bytearray(SECTOR)
    bs[0:3] = b"\xEB\x3C\x90"
    bs[3:11] = b"RAMDISK "
    struct.pack_into("<HBHBHHBHHHII", bs, 11,
                     SECTOR,  # bytes per sector
                     1,       # sectors per cluster
                     1,       # reserved sectors (the boot sector)
                     2,       # FAT copies
                     16,      # root directory entries (one sector)
                     TOTAL,   # total sectors
                     0xF8,    # media descriptor
                     1,       # sectors per FAT
                     32,      # sectors per track
                     2,       # heads
                     0,       # hidden sectors
                     0)       # total sectors (32-bit field, unused)
    struct.pack_into("<BBBI", bs, 36, 0x80, 0, 0x29, 0x52414D44)
    bs[43:54] = b"RAMDISK    "
    bs[54:62] = b"FAT12   "
    bs[510:512] = b"\x55\xAA"
    return bytes(bs)


def fat():
    # Entries 0 and 1 are reserved; entry 2 (HELLO.TXT's only cluster) is end of chain.
    f = bytearray(SECTOR)
    f[0:5] = b"\xF8\xFF\xFF\xFF\x0F"
    return bytes(f)


def root_dir():
    d = bytearray(SECTOR)
    d[0:11] = b"RAMDISK    "
    d[11] = 0x08
    entry = bytearray(32)
    entry[0:11] = b"HELLO   TXT"
    entry[11] = 0x20
    struct.pack_into("<HHHI", entry, 22, 0, 0x5B50, 2, len(HELLO))
    struct.pack_into("<H", entry, 16, 0x5B50)
    struct.pack_into("<H", entry, 18, 0x5B50)
    d[32:64] = entry
    return bytes(d)


def hello():
    return HELLO + bytes(SECTOR - len(HELLO))


# Layout: 0 boot, 1-2 FATs, 3 root directory, 4 onward clusters 2 onward.
SECTORS = [(0, boot_sector()), (1, fat()), (2, fat()), (3, root_dir()), (4, hello())]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "src", "iop", "image.c")
    with open(out, "w", newline="\n") as f:
        f.write("/* Generated by mkimage.py. */\n\n")
        f.write('#include "image.h"\n\n')
        f.write("const unsigned int ramdisk_sector_count = %d;\n\n" % TOTAL)
        f.write("const struct ramdisk_seed ramdisk_seed[] = {\n")
        for lba, data in SECTORS:
            f.write("    {%d, {\n" % lba)
            for i in range(0, SECTOR, 16):
                f.write("        " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
            f.write("    }},\n")
        f.write("};\n\n")
        f.write("const unsigned int ramdisk_seed_count = sizeof(ramdisk_seed) / sizeof(ramdisk_seed[0]);\n")


if __name__ == "__main__":
    main()
